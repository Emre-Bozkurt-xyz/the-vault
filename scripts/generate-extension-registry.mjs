/**
 * Generates the extension registry files from the folders under `extensions/`
 * (`docs/23_EXTENSION_SDK_PLAN.md` §11, §18.1):
 *
 *   extensions/manifests.ts        every manifest (isomorphic)
 *   extensions/registry.render.ts  every render module (isomorphic; light by
 *                                  contract, components are lazy inside them)
 *   extensions/registry.client.ts  manifests + lazy editor loaders
 *   extensions/registry.server.ts  manifests + server modules ("server-only")
 *
 * A folder is an extension when it has `manifest.ts`; `render.tsx`,
 * `editor.tsx` and `server.ts` are optional. Output is sorted by folder name so
 * it is deterministic. These are the only files core may import from
 * `extensions/`, which is why they are generated rather than hand-kept: adding
 * an extension is adding a folder.
 *
 *   node scripts/generate-extension-registry.mjs          write if changed
 *   node scripts/generate-extension-registry.mjs --check  exit 1 if stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HEADER = `// Generated by scripts/generate-extension-registry.mjs. Do not edit by hand.
// Run \`npm run ext:registry\` after adding or removing an extension folder.
`;

function identifier(folder) {
  return folder.replace(/[-_.]+([a-z0-9])/gi, (_match, next) =>
    next.toUpperCase(),
  );
}

function hasModule(dir, names) {
  return names.some((name) => fs.existsSync(path.join(dir, name)));
}

/** Extension folders under `extensionsDir`, sorted, with the modules each has. */
export function scanExtensions(extensionsDir) {
  return fs
    .readdirSync(extensionsDir, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isDirectory() &&
        fs.existsSync(path.join(extensionsDir, entry.name, "manifest.ts")),
    )
    .map((entry) => entry.name)
    .sort()
    .map((folder) => {
      const dir = path.join(extensionsDir, folder);
      return {
        folder,
        id: identifier(folder),
        render: hasModule(dir, ["render.tsx", "render.ts"]),
        editor: hasModule(dir, ["editor.tsx", "editor.ts"]),
        server: hasModule(dir, ["server.ts"]),
      };
    });
}

/** Contents of each generated file, keyed by path relative to `extensionsDir`. */
export function renderRegistryFiles(extensions) {
  const manifestImports = extensions.map(
    (ext) => `import ${ext.id}Manifest from "./${ext.folder}/manifest";`,
  );
  const manifestList = extensions.map((ext) => `  ${ext.id}Manifest,`);

  const manifests = `${HEADER}import type { ExtensionManifest } from "@/lib/extension-api";

${manifestImports.join("\n")}

export const extensionManifests: readonly ExtensionManifest[] = [
${manifestList.join("\n")}
];
`;

  const clientEntries = extensions.map((ext) => {
    const loaders = [
      `manifest: ${ext.id}Manifest`,
      ext.editor ? `editor: () => import("./${ext.folder}/editor")` : null,
    ].filter(Boolean);
    return `  {\n    ${loaders.join(",\n    ")},\n  },`;
  });

  const client = `${HEADER}//
// Editor modules are referenced only through \`import()\`, so each is its own
// chunk, loaded for users who enabled the extension (plan §9).
import type { EditorModule, ExtensionManifest } from "@/lib/extension-api";

${manifestImports.join("\n")}

export type ClientExtensionEntry = {
  manifest: ExtensionManifest;
  editor?: () => Promise<{ default: EditorModule }>;
};

export const clientExtensions: readonly ClientExtensionEntry[] = [
${clientEntries.join("\n")}
];
`;

  const serverImports = extensions
    .filter((ext) => ext.server)
    .map((ext) => `import ${ext.id}Server from "./${ext.folder}/server";`);
  const serverEntries = extensions.map(
    (ext) =>
      `  { manifest: ${ext.id}Manifest, server: ${ext.server ? `${ext.id}Server` : "null"} },`,
  );

  const server = `${HEADER}import "server-only";

import type { ExtensionManifest } from "@/lib/extension-api";
import type { ExtensionServerModule } from "@/lib/extension-api/server";

${manifestImports.join("\n")}
${serverImports.length ? `\n${serverImports.join("\n")}\n` : ""}
export type ServerExtensionEntry = {
  manifest: ExtensionManifest;
  server: ExtensionServerModule | null;
};

export const serverExtensions: readonly ServerExtensionEntry[] = [
${serverEntries.join("\n")}
];
`;

  const renderImports = extensions
    .filter((ext) => ext.render)
    .map((ext) => `import ${ext.id}Render from "./${ext.folder}/render";`);
  const renderList = extensions
    .filter((ext) => ext.render)
    .map((ext) => `  ${ext.id}Render,`);

  const render = `${HEADER}//
// Render modules are imported statically on both server and client, so they
// must stay light: definitions plus lazy component loaders (plan §4, §9).
import type { RenderModule } from "@/lib/extension-api";
${renderImports.length ? `\n${renderImports.join("\n")}\n` : ""}
export const renderModules: readonly RenderModule[] = [
${renderList.join("\n")}
];
`;

  return {
    "manifests.ts": manifests,
    "registry.render.ts": render,
    "registry.client.ts": client,
    "registry.server.ts": server,
  };
}

function normalize(text) {
  return text.replace(/\r\n/g, "\n");
}

/** Paths (relative to `extensionsDir`) whose on-disk content is out of date. */
export function staleRegistryFiles(extensionsDir) {
  const files = renderRegistryFiles(scanExtensions(extensionsDir));
  return Object.entries(files)
    .filter(([name, contents]) => {
      const target = path.join(extensionsDir, name);
      return (
        !fs.existsSync(target) ||
        normalize(fs.readFileSync(target, "utf8")) !== contents
      );
    })
    .map(([name]) => name);
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const extensionsDir = path.join(root, "extensions");
  const check = process.argv.includes("--check");
  const stale = staleRegistryFiles(extensionsDir);

  if (check) {
    if (stale.length > 0) {
      console.error(
        `Extension registry is stale: ${stale.join(", ")}. Run \`npm run ext:registry\`.`,
      );
      process.exit(1);
    }
    return;
  }

  const files = renderRegistryFiles(scanExtensions(extensionsDir));
  for (const name of stale) {
    fs.writeFileSync(path.join(extensionsDir, name), files[name]);
    console.log(`extensions/${name} updated`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
